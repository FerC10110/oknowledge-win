"""Editing the vault: the only module that changes or removes a user's note.

The rule the whole project is built on is that a link is never lost, so these
tests spend most of their effort on what happens when a write goes wrong.
"""

import contextlib

import pytest

from oknowledge.config import Config
from oknowledge.model import Mention, Note
from oknowledge.urls import search_url
from oknowledge.queue import Locked
from oknowledge.vault import (
    BadCategory,
    IndexesStale,
    all_notes,
    categories,
    clean_category,
    delete_note,
    find_note,
    index_path,
    read_note,
    rebuild_indexes,
    rename_category,
    trash_dir,
    update_note,
    write_note,
)


def make(tmp_path):
    vault = tmp_path / "vault"
    (vault / "oknowledge" / "links").mkdir(parents=True)
    return Config(vault=vault)


def note(id, title, category, tags=("x",)):
    return Note(id=id, url=f"https://e.com/{id}", title=title, category=category,
                tags=list(tags), type="article", source="e.com", saved="2026-10-03",
                summary=f"Resumen de {title}.", points=[])


# --- moving a note between categories ---------------------------------------

def test_moving_a_note_to_another_category_updates_both_indexes(tmp_path):
    cfg = make(tmp_path)
    write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    rebuild_indexes(cfg, "es")

    update_note(cfg, "a1", "es", category="Seguridad")

    assert not index_path(cfg, "Redes").exists()
    assert "WireGuard" in index_path(cfg, "Seguridad").read_text(encoding="utf-8")


def test_editing_tags_normalizes_them(tmp_path):
    cfg = make(tmp_path)
    path = write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    update_note(cfg, "a1", "es", tags=["VPN", "Programación", "vpn"])
    assert read_note(path).tags == ["vpn", "programacion"]


def test_editing_does_not_lose_the_body(tmp_path):
    cfg = make(tmp_path)
    original = note("a1", "WireGuard", "Redes")
    original.body = "El texto entero."
    path = write_note(cfg, original, "es")
    update_note(cfg, "a1", "es", category="Seguridad")
    assert read_note(path).body == "El texto entero."


def test_editing_writes_in_place_and_keeps_the_file_name(tmp_path):
    cfg = make(tmp_path)
    path = write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    written = update_note(cfg, "a1", "es", category="Seguridad")
    assert written == path
    assert [p.name for p in sorted(cfg.links_dir.glob("*.md"))] == [path.name]


def test_a_failed_write_leaves_the_note_exactly_as_it_was(tmp_path, monkeypatch):
    """Ruling 1: never unlink before writing. A full disk must cost the edit,
    not the note."""
    cfg = make(tmp_path)
    path = write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    before = path.read_text(encoding="utf-8")

    def boom(*args, **kwargs):
        raise OSError(28, "No space left on device")

    monkeypatch.setattr("oknowledge.vault.atomic_write", boom)
    with pytest.raises(OSError):
        update_note(cfg, "a1", "es", category="Seguridad")

    assert path.exists()
    assert path.read_text(encoding="utf-8") == before


def test_rebuilding_after_an_edit_uses_the_language_it_was_given(tmp_path):
    cfg = make(tmp_path)
    write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    update_note(cfg, "a1", "en", category="Security")
    assert "Generated by oknowledge" in index_path(cfg, "Security").read_text(encoding="utf-8")


def test_updating_a_link_that_does_not_exist_is_none(tmp_path):
    assert update_note(make(tmp_path), "zzz", "es", category="X") is None


# --- category names the user types ------------------------------------------

@pytest.mark.parametrize("bad", [
    "../../etc", "a/b", "a\\b", "..", ".hidden", "", "   ", "x\ty", "a\x00b",
    "con\x1ftrol", "a" * 200,
])
def test_a_category_that_could_leave_the_folder_is_refused(tmp_path, bad):
    cfg = make(tmp_path)
    path = write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    with pytest.raises(BadCategory):
        update_note(cfg, "a1", "es", category=bad)
    assert read_note(path).category == "Redes"
    assert clean_category(bad) is None


def test_a_refused_category_writes_nothing_anywhere(tmp_path):
    cfg = make(tmp_path)
    write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    before = sorted(p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*"))
    with pytest.raises(BadCategory):
        update_note(cfg, "a1", "es", category="../../../etc/passwd")
    with pytest.raises(BadCategory):
        rename_category(cfg, "Redes", "../../../etc/passwd", "es")
    assert sorted(p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*")) == before


def test_a_plain_name_with_accents_and_spaces_is_kept_as_typed(tmp_path):
    assert clean_category("  Programación en C  ") == "Programación en C"


# --- deleting ---------------------------------------------------------------

def test_deleting_a_note_removes_it_from_its_index(tmp_path):
    cfg = make(tmp_path)
    write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    write_note(cfg, note("b2", "SSH", "Redes"), "es")
    rebuild_indexes(cfg, "es")

    assert delete_note(cfg, "a1", "es") is not None

    text = index_path(cfg, "Redes").read_text(encoding="utf-8")
    assert "WireGuard" not in text and "SSH" in text


def test_deleting_moves_the_note_to_the_trash_instead_of_destroying_it(tmp_path):
    """Ruling 2: delete fires from a browser POST; a mis-click must be undoable."""
    cfg = make(tmp_path)
    path = write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    before = path.read_text(encoding="utf-8")

    moved = delete_note(cfg, "a1", "es")

    assert not path.exists()
    assert moved == trash_dir(cfg) / path.name
    assert moved.read_text(encoding="utf-8") == before


def test_two_deleted_notes_with_the_same_name_do_not_clobber_each_other(tmp_path):
    cfg = make(tmp_path)
    first = write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    one = delete_note(cfg, "a1", "es")
    second = write_note(cfg, note("b2", "WireGuard", "Redes"), "es")
    assert second.name == first.name          # same date, same title, same file name
    two = delete_note(cfg, "b2", "es")

    assert one != two
    assert one.exists() and two.exists()
    assert "a1" in one.read_text(encoding="utf-8")
    assert "b2" in two.read_text(encoding="utf-8")


def test_the_trash_is_not_scanned_indexed_or_counted(tmp_path):
    cfg = make(tmp_path)
    write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    write_note(cfg, note("b2", "SSH", "Redes"), "es")
    delete_note(cfg, "a1", "es")
    rebuild_indexes(cfg, "es")

    assert [n.id for n in all_notes(cfg)] == ["b2"]
    assert categories(cfg) == {"Redes": 1}
    assert "WireGuard" not in index_path(cfg, "Redes").read_text(encoding="utf-8")
    assert not (cfg.root / "trash" / "Redes.md").exists()


def test_deleting_a_link_that_does_not_exist_changes_nothing(tmp_path):
    cfg = make(tmp_path)
    write_note(cfg, note("a1", "WireGuard", "Redes"), "es")
    before = sorted(p.name for p in cfg.links_dir.iterdir())
    assert delete_note(cfg, "zzz", "es") is None
    assert sorted(p.name for p in cfg.links_dir.iterdir()) == before


def test_deleting_leaves_a_note_of_yours_alone(tmp_path):
    cfg = make(tmp_path)
